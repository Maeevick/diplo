//! Every picture of the game, drawn as text: one character a pixel, `.` see-through, the others the PICO-8 palette's
//! sixteen colours by their hexadecimal index, `#` pure white for letters to be tinted. Animals face right; the game flips them to face left.

pub type Picture = &'static [&'static str];

/// PICO-8's sixteen colours, by index.
pub const PALETTE: [[u8; 3]; 16] = [
    [0x00, 0x00, 0x00],
    [0x1d, 0x2b, 0x53],
    [0x7e, 0x25, 0x53],
    [0x00, 0x87, 0x51],
    [0xab, 0x52, 0x36],
    [0x5f, 0x57, 0x4f],
    [0xc2, 0xc3, 0xc7],
    [0xff, 0xf1, 0xe8],
    [0xff, 0x00, 0x4d],
    [0xff, 0xa3, 0x00],
    [0xff, 0xec, 0x27],
    [0x00, 0xe4, 0x36],
    [0x29, 0xad, 0xff],
    [0x83, 0x76, 0x9c],
    [0xff, 0x77, 0xa8],
    [0xff, 0xcc, 0xaa],
];

/// Width and height of a picture, and its pixels as RGBA, row by row from the top.
pub fn rgba(picture: &[&str]) -> (u32, u32, Vec<u8>) {
    let width = picture[0].len() as u32;
    let pixels = picture
        .iter()
        .flat_map(|row| row.chars())
        .flat_map(|pixel| match pixel {
            '#' => [0xff; 4],
            _ => match pixel.to_digit(16) {
                Some(index) => {
                    let [r, g, b] = PALETTE[index as usize];
                    [r, g, b, 0xff]
                }
                None => [0, 0, 0, 0],
            },
        })
        .collect();
    (width, picture.len() as u32, pixels)
}

